# Godot 4 Key enum values for the key names used in KGSM genre configs.
KEYCODES = {
    "SPACE": 32,
    "ZERO": 48, "ONE": 49, "TWO": 50, "THREE": 51, "FOUR": 52,
    "FIVE": 53, "SIX": 54, "SEVEN": 55, "EIGHT": 56, "NINE": 57,
    "ESCAPE": 4194305, "TAB": 4194306, "ENTER": 4194309,
    "PAUSE": 4194313,
    "LEFT": 4194319, "UP": 4194320, "RIGHT": 4194321, "DOWN": 4194322,
    "PAGEUP": 4194323, "PAGEDOWN": 4194324,
    "SHIFT": 4194325, "CTRL": 4194326, "ALT": 4194328,
}


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def canonical_json(obj: object) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"))


def gd_literal(value: object) -> str:
    """Render a JSON-ish value as a GDScript literal."""
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(gd_literal(v) for v in value) + "]"
    if isinstance(value, dict):
        inner = ", ".join(
            f"{json.dumps(str(k))}: {gd_literal(v)}" for k, v in value.items()
        )
        return "{" + inner + "}"
    raise TypeError(f"unsupported config value: {type(value).__name__}")


def snake_case(name: str) -> str:
    out = []
    for ch in name:
        if ch.isupper():
            out.append("_")
            out.append(ch.lower())
        elif ch == "-":
            out.append("_")
        else:
            out.append(ch)
    return "".join(out).strip("_")


def keycode_for(name: str, warnings: list[str], action: str) -> int | None:
    upper = str(name).strip().upper()
    if upper in KEYCODES:
        return KEYCODES[upper]
    if len(upper) == 1 and ("A" <= upper <= "Z" or "0" <= upper <= "9"):
        return ord(upper)
    warnings.append(f"input: unknown key {name!r} for action {action!r}; skipped")
    return None


def project_godot_text(
    *,
    project_name: str,
    width: int,
    height: int,
    actions: dict[str, str],
    pixel_art: bool,
    warnings: list[str],
) -> str:
    """Render project.godot with window, input map, autoload and renderer."""
    features = ", ".join(f'"{f}"' for f in GODOT_FEATURES)
    lines = [
        "; Engine configuration file.",
        "; Generated by the KGSM Godot 4 exporter (FR-021).",
        "config_version=5",
        "",
        "[application]",
        f"config/name={json.dumps(project_name)}",
        'run/main_scene="res://scenes/main.tscn"',
        f"config/features=PackedStringArray({features})",
        'config/icon="res://icon.svg"',
        "",
        "[autoload]",
        'GameConfig="*res://scripts/game_config.gd"',
        "",
        "[display]",
        f"window/size/viewport_width={int(width)}",
        f"window/size/viewport_height={int(height)}",
        'window/stretch/mode="canvas_items"',
        'window/stretch/aspect="keep"',
        "",
        "[input]",
    ]
    for action in sorted(actions):
        code = keycode_for(actions[action], warnings, action)
        if code is None:
            continue
        lines.append(action + "={")
        lines.append('"deadzone": 0.2,')
        lines.append(
            '"events": [Object(InputEventKey,"resource_local_to_scene":false,'
            '"resource_name":"","device":-1,"window_id":0,"alt_pressed":false,'
            '"shift_pressed":false,"ctrl_pressed":false,"meta_pressed":false,'
            f'"pressed":false,"keycode":0,"physical_keycode":{code},"key_label":0,'
            '"unicode":0,"location":0,"echo":false,"script":null)'
        )
        lines.append("]")
        lines.append("}")
    lines += [
        "",
        "[rendering]",
        'renderer/rendering_method="gl_compatibility"',
        "textures/canvas_textures/default_texture_filter="
        + ("0" if pixel_art else "1"),
        "",
    ]
    return "\n".join(lines)


def scene_text(
    *, resources: list[str], sub_resources: list[str], nodes: list[str]
) -> str:
    """Render a Godot 4 .tscn with a correct load_steps count."""
    ext = sum(1 for r in resources if r.startswith("[ext_resource"))
    sub = sum(1 for r in sub_resources if r.startswith("[sub_resource"))
    load_steps = ext + sub + 1
    parts = [f"[gd_scene load_steps={load_steps} format=3]", ""]
    parts.extend(resources)
    if resources:
        parts.append("")
    parts.extend(sub_resources)
    if sub_resources:
        parts.append("")
    parts.extend(nodes)
    return "\n".join(parts).rstrip() + "\n"


def main_tscn(*, instances: list[tuple[str, str]]) -> str:
    """Main scene: Node2D root running scripts/main.gd plus instances."""
    resources = ['[ext_resource type="Script" path="res://scripts/main.gd" id="1"]']
    for i, (_name, scene) in enumerate(instances, start=2):
        resources.append(
            f'[ext_resource type="PackedScene" path="{scene}" id="{i}"]'
        )
    nodes = [
        '[node name="Main" type="Node2D" groups=["game"]]',
        "process_mode = 3",
        'script = ExtResource("1")',
        "",
    ]
    for i, (name, _scene) in enumerate(instances, start=2):
        nodes.append(
            f'[node name="{name}" parent="." instance=ExtResource("{i}")]'
        )
        if name == "HUD":
            nodes.append("process_mode = 3")
        nodes.append("")
    return scene_text(resources=resources, sub_resources=[], nodes=nodes)


def game_config_gd() -> str:
    return '''extends Node
## KGSM GameConfig autoload: loads res://config.json once and exposes it.
## Also persists local best scores to user://kgsm_save.cfg.

var data: Dictionary = {}
var seed_value: int = 0

const SAVE_PATH := "user://kgsm_save.cfg"


func _ready() -> void:
	process_mode = Node.PROCESS_MODE_ALWAYS
	var path := "res://config.json"
	if not FileAccess.file_exists(path):
		push_warning("GameConfig: config.json missing; using defaults")
		return
	var parsed: Variant = JSON.parse_string(FileAccess.get_file_as_string(path))
	if typeof(parsed) != TYPE_DICTIONARY:
		push_error("GameConfig: config.json is not a JSON object")
		return
	data = parsed
	seed_value = int(data.get("seed", 0))
	seed(seed_value)


func section(name: String) -> Dictionary:
	var value: Variant = data.get(name, {})
	if typeof(value) == TYPE_DICTIONARY:
		return value
	return {}


func world_size() -> Vector2:
	var w: Dictionary = section("world")
	return Vector2(float(w.get("width", 960.0)), float(w.get("height", 540.0)))


func sprite_path(role: String) -> String:
	var assets: Dictionary = section("assets")
	var sprites: Variant = assets.get("sprites", {})
	if typeof(sprites) == TYPE_DICTIONARY and sprites.has(role):
		return "res://" + str(sprites[role])
	return ""


func load_best(key: String, default: int = 0) -> int:
	var cfg := ConfigFile.new()
	if cfg.load(SAVE_PATH) != OK:
		return default
	return int(cfg.get_value("best", key, default))


func save_best(key: String, value: int) -> void:
	var cfg := ConfigFile.new()
	cfg.load(SAVE_PATH)
	cfg.set_value("best", key, value)
	cfg.save(SAVE_PATH)
'''


