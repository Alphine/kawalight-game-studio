def build_manifest(
    *,
    project_name: str,
    genre: str,
    template_id: str,
    template_version: str,
    config: dict,
    assets: list[dict],
    warnings: list[str],
) -> dict:
    """Neutral export manifest (FR-018 shape; validated by schema in CI)."""
    return {
        "manifestVersion": "1.0.0",
        "projectName": project_name,
        "genre": genre,
        "template": {"id": template_id, "version": template_version},
        "exportedAt": datetime.now(timezone.utc).isoformat(),
        "configHash": "sha256:" + sha256_hex(canonical_json(config).encode()),
        "runtime": {"name": "godot", "version": GODOT_VERSION},
        "assets": assets,
        "warnings": warnings,
    }


def _png_chunk(tag: bytes, payload: bytes) -> bytes:
    return (
        struct.pack(">I", len(payload))
        + tag
        + payload
        + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)
    )


def placeholder_png(
    *, width: int = 32, height: int = 32, color: tuple[int, int, int] = (200, 70, 90)
) -> bytes:
    """Minimal valid RGBA PNG (stdlib zlib) used when starter art is missing."""
    width = max(4, min(int(width), 256))
    height = max(4, min(int(height), 256))
    r, g, b = (max(0, min(int(c), 255)) for c in color)
    dark = (r // 3, g // 3, b // 3, 255)
    fill = (r, g, b, 255)
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for x in range(width):
            border = x < 2 or y < 2 or x >= width - 2 or y >= height - 2
            cross = abs(x - y) < 2 or abs(x + y - width) < 2
            px = dark if border else (fill if not cross else (255, 255, 255, 255))
            rows.extend(px)
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", ihdr)
        + _png_chunk(b"IDAT", zlib.compress(bytes(rows), 9))
        + _png_chunk(b"IEND", b"")
    )
